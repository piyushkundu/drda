// Build Trie from all sources
// ══════════════════════════════════════════════
const _allWords: string[] = [];
const seen = new Set<string>();

// Priority order: letter phrases first, then social audit, then gov, etc.
const allSources = [
  letterPhrases, socialAuditTerms, govTerms, govSchemes,
  applicationTerms, upDistricts, bagpatBlocks, majorCities,
  timeTerms, connectorWords
];

for (const list of allSources) {
  for (const w of list) {
    if (!seen.has(w)) {
      seen.add(w);
      _allWords.push(w);
    }
  }
}

export const allDictionaryWords = _allWords;

// ─── Trie for fast prefix lookup ───
interface TrieNode {
  children: Map<string, TrieNode>;
  words: string[];
}

function createTrieNode(): TrieNode {
  return { children: new Map(), words: [] };
}

const trieRoot = createTrieNode();

for (const word of _allWords) {
  let node = trieRoot;
  for (const char of word) {
    if (!node.children.has(char)) {
      node.children.set(char, createTrieNode());
    }
    node = node.children.get(char)!;
    node.words.push(word);
  }
}

/**
 * Get completions for a prefix using Trie lookup.
 * Works character-by-character — even a single character returns results.
 */
export function getCompletions(prefix: string, limit = 5): string[] {
  if (!prefix || prefix.trim() === '') return [];

  let node = trieRoot;
  for (const char of prefix) {
    const child = node.children.get(char);
    if (!child) return [];
    node = child;
  }

  const results: string[] = [];
  for (const w of node.words) {
    if (w !== prefix) {
      results.push(w);
      if (results.length >= limit) break;
    }
  }
  return results;
}
